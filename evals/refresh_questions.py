#!/usr/bin/env python3
"""Re-derive every pinned figure in evals/questions.yaml from the generators.

The six seed questions are an eval TRIPLE each (prompt, documented trap, derived
ground truth + resolving context). Their numbers must never be typed by hand, so
this script renders the file from a template with values from
generators/measures.py and generators/identity_measures.py. Run it after any
generator/config change, in the same commit as the ground-truth re-derivation:

    python evals/refresh_questions.py
"""
from __future__ import annotations

import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

import config  # noqa: E402
from generators import dataset  # noqa: E402
from generators.identity_measures import AS_OF, GMV_END, GMV_START, derive_identity_measures  # noqa: E402
from generators.measures import five_revenues  # noqa: E402

OUT = REPO_ROOT / "evals" / "questions.yaml"

TEMPLATE = """# Eval questions for the revenue and customer-identity slices.
#
# GENERATED by evals/refresh_questions.py — every figure below is derived from the
# generators (never hand-typed). Re-run after any generator/config change.
#
# Each question is an eval TRIPLE: a natural prompt that looks easy, a documented
# trap (the silent-SQL failure it invites), and a pointer to derived ground truth
# + the context artifact that should defuse it. Questions read like real Slack
# messages, not contorted gotchas — the difficulty lives in the warehouse.

dataset_version: {version}

questions:
  - id: revenue_q1_2024_unqualified
    prompt: "What was our revenue in Q1 2024?"
    persona: null            # unknown requester -> canonical default applies
    ground_truth: context/ground_truth/revenue_q1_2024.md
    canonical_answer: {{ measure: recognized_revenue, value: {rec} }}
    context_required:
      - context/metrics/revenue.yml
      - context/guides/personas.md
    trap: >
      "Revenue" is ambiguous across five measures. The seductive wrong answer is
      GMV or net_revenue (in-period sales). Recognized revenue is higher because
      of ratable recognition from prior-period subscriptions booked in the Q4
      budget flush.
    silent_fail_values: [{gmv}, {net}, {billed}, {cash}]

  - id: revenue_q1_2024_marketing
    prompt: "Marcus is building the QBR deck — what's our Q1 2024 revenue for the growth chart?"
    persona: marketing
    ground_truth: context/ground_truth/revenue_q1_2024.md
    canonical_answer: {{ measure: gmv, value: {gmv} }}
    context_required:
      - context/guides/personas.md
    trap: >
      Persona flips the canonical default: marketing's "revenue" is GMV, not the
      CFO's recognized number. Tests whether the agent uses persona context.

  - id: revenue_q1_2024_cash
    prompt: "How much revenue did we actually collect in Q1 2024?"
    persona: treasury
    ground_truth: context/ground_truth/revenue_q1_2024.md
    canonical_answer: {{ measure: collected_cash, value: {cash} }}
    context_required:
      - context/metrics/revenue.yml
    trap: >
      "Actually collected" is a strong signal for collected_cash, but an agent
      anchored on a generic revenue definition may still return recognized/net.

  - id: identity_customer_count_2025
    prompt: >
      How many customers did we have at the end of 2025 across Stripe, Salesforce,
      Shopify, and the app? Give me the canonical business customer count, and also
      report unresolved source IDs and the resolution null rate.
    persona: operations
    ground_truth: context/ground_truth/customer_identity_2021_migration.md
    canonical_answer:
      measure: ordered_canonical_customer_count
      value: {ordered}
      unresolved_source_id_count: {unresolved}
      resolution_null_rate: {null_rate}
    context_required:
      - context/guides/customer_identity.md
      - context/semantic/customer_identity.view.lkml
    pinned_scope: {{ as_of: "{as_of}" }}
    trap: >
      Counting raw IDs answers at alias grain ({naive:,}), while an inner join silently
      retains only {inner:,} aliases. Counting all resolved app profiles returns {profiles:,},
      including profiles with no orders. The business customer count is the {ordered:,}
      ordered canonical customers, with unresolved quality reported separately.
    silent_fail_values: [{naive}, {inner}, {profiles}]

  - id: identity_pre_migration_shopify
    prompt: >
      Of the pre-migration Shopify customer IDs created before the 2021 identity migration, how
      many are tied to an app customer as of the end of 2025, and how many are missing?
    persona: data_platform
    ground_truth: context/ground_truth/customer_identity_2021_migration.md
    canonical_answer:
      measure: pre_migration_shopify_resolved_count
      value: {shp_resolved}
      missing_count: {shp_missing}
    context_required:
      - context/guides/customer_identity.md
      - context/semantic/customer_identity.view.lkml
    pinned_scope:
      migration_cutoff: "{migration}"
      as_of: "{as_of}"
    trap: >
      Returning all {shp_observed:,} observed pre-migration Shopify aliases ignores the planted
      crosswalk gap; returning only the {shp_missing:,} missing aliases reverses the question.
      The requested result is {shp_resolved:,} tied IDs and {shp_missing:,} missing IDs.
    silent_fail_values: [{shp_observed}]

  - id: identity_multi_source_gmv_2024
    prompt: >
      What was 2024 GMV from customers we could resolve in at least two distinct
      source systems as of 2025-12-31? Include the order count and eligible canonical
      customer count.
    persona: finance
    ground_truth: context/ground_truth/customer_identity_2021_migration.md
    canonical_answer:
      measure: correct_multi_source_gmv
      value: {ms_gmv}
      order_count: {ms_orders}
      eligible_canonical_customer_count: {ms_customers}
    context_required:
      - context/guides/customer_identity.md
      - context/semantic/customer_identity.view.lkml
    pinned_scope:
      gmv_start: "{gmv_start}"
      gmv_end: "{gmv_end}"
      as_of: "{as_of}"
    trap: >
      Joining orders directly to the long resolved identity bridge fans each order
      out once per alias, including historical Stripe aliases, and produces the
      plausible but wrong ${fan_gmv:,.2f} across {fan_rows:,} rows. Deduplicate the eligible
      canonical customer set before filtering order facts.
    silent_fail_values: [{fan_gmv}]
"""


def main() -> int:
    tables = dataset.generate()
    p = config.TARGET_PERIOD
    rev = five_revenues(tables, p["start"], p["end"])
    idm = derive_identity_measures(tables, as_of=AS_OF, gmv_start=GMV_START, gmv_end=GMV_END)
    text = TEMPLATE.format(
        version=config.DATASET_VERSION,
        rec=rev["recognized_revenue"], gmv=rev["gmv"], net=rev["net_revenue"],
        billed=rev["billed_revenue"], cash=rev["collected_cash"],
        ordered=idm["ordered_canonical_customer_count"],
        unresolved=idm["unresolved_source_id_count"],
        null_rate=idm["resolution_null_rate"],
        naive=idm["naive_distinct_source_id_count"],
        inner=idm["inner_join_retained_source_id_count"],
        profiles=idm["distinct_resolved_canonical_id_count"],
        as_of=idm["as_of"], migration=idm["identity_migration_date"],
        shp_resolved=idm["pre_migration_shopify_resolved_count"],
        shp_missing=idm["pre_migration_shopify_missing_count"],
        shp_observed=idm["pre_migration_shopify_observed_count"],
        ms_gmv=idm["correct_multi_source_gmv"], ms_orders=idm["correct_multi_source_order_count"],
        ms_customers=idm["multi_source_canonical_customer_count"],
        gmv_start=idm["gmv_start"], gmv_end=idm["gmv_end"],
        fan_gmv=idm["unsafe_fanout_gmv"], fan_rows=idm["unsafe_fanout_order_row_count"],
    )
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO_ROOT)} ({config.DATASET_VERSION})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
